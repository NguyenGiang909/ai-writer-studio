export type Lang = "vi" | "en";
export const LANG_COOKIE = "writer-lang";

/** t(lang, "Chuỗi tiếng Việt", {name}) — thay {name} bằng giá trị. */
export function t(lang: Lang | undefined, vi: string, params?: Record<string, string | number>): string {
  let s = lang === "en" ? (EN[vi] ?? vi) : vi;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

